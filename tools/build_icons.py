#!/usr/bin/env python3
"""Builds the icon fonts of the screens (docs/architecture.md section 7): a subset of the Material
Design Icons, converted by lv_font_conv into plain C files of LVGL.

    python tools/build_icons.py            # download the MDI font once, convert, write the files
    python tools/build_icons.py --check    # only check that every name has a glyph

The names are the icon list of core (components/core/src/icons.cpp, the names a tile may use)
and the few glyphs the screens draw themselves (UI_GLYPHS). The output is committed, so the build
needs neither Node.js nor the network; run this after the list changed:

    components/ui/src/fonts/hc_mdi_<size>.c   one font per size of SIZES
    components/ui/src/icon_glyphs.inc         {"name", "<UTF-8 of the glyph>"}, sorted by name
    web/icons.svg                             one <symbol id="mdi-<name>"> per icon for the web editor

Needs Node.js (npx runs lv_font_conv). The MDI font and the icon paths (@mdi/svg, one small file per
icon) are downloaded into build/mdi/.
"""

import argparse
import re
import shutil
import subprocess
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MDI_VERSION = "7.4.47"
MDI_URL = f"https://cdn.jsdelivr.net/npm/@mdi/font@{MDI_VERSION}"
MDI_SVG_URL = f"https://cdn.jsdelivr.net/npm/@mdi/svg@{MDI_VERSION}/svg"
CACHE = ROOT / "build" / "mdi"
FONT_CONV = ["npx", "--yes", "lv_font_conv@1.5.3"]

# (size in pixels, bits per pixel): tiles and buttons, and area tiles and panels. 2 bpp for the
# large size: its edges are smooth enough and it halves the bitmap.
SIZES = ((24, 4), (48, 2))

# drawn by the screens, not named by tiles
UI_GLYPHS = ("arrow-left", "plus", "minus", "creation", "fire", "snowflake", "sun-snowflake-variant",
             "thermostat-auto", "record")

ICON_LIST = ROOT / "components" / "core" / "src" / "icons.cpp"
OUT_FONTS = ROOT / "components" / "ui" / "src" / "fonts"
OUT_TABLE = ROOT / "components" / "ui" / "src" / "icon_glyphs.inc"
OUT_SPRITE = ROOT / "web" / "icons.svg"


def tile_icons() -> list[str]:
    text = ICON_LIST.read_text(encoding="utf-8")
    block = re.search(r"kIcons\[\] = \{(.*?)\};", text, re.S)
    if not block:
        sys.exit(f"no kIcons list in {ICON_LIST}")
    return re.findall(r'"([a-z0-9-]+)"', block.group(1))


def fetch(name: str) -> Path:
    path = CACHE / name
    if not path.exists():
        CACHE.mkdir(parents=True, exist_ok=True)
        url = f"{MDI_URL}/{'css' if name.endswith('.css') else 'fonts'}/{name}"
        print(f"downloading {url}")
        with urllib.request.urlopen(url, timeout=60) as response:
            path.write_bytes(response.read())
    return path


def svg_path(name: str) -> str:
    """The path data of one icon (24 x 24, filled)."""
    path = CACHE / "svg" / f"{name}.svg"
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        with urllib.request.urlopen(f"{MDI_SVG_URL}/{name}.svg", timeout=60) as response:
            path.write_bytes(response.read())
    found = re.search(r'<path d="([^"]+)"', path.read_text(encoding="utf-8"))
    if not found:
        sys.exit(f"no path in {path}")
    return found.group(1)


def write_sprite(names: list[str]) -> None:
    lines = ['<svg xmlns="http://www.w3.org/2000/svg" style="display:none">',
             f"<!-- Generated by tools/build_icons.py from MDI {MDI_VERSION}; do not edit. -->"]
    lines += [f'<symbol id="mdi-{n}" viewBox="0 0 24 24"><path d="{svg_path(n)}"/></symbol>' for n in names]
    lines.append("</svg>")
    OUT_SPRITE.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{OUT_SPRITE.relative_to(ROOT)}: {OUT_SPRITE.stat().st_size // 1024} KB")


def codepoints() -> dict[str, int]:
    css = fetch("materialdesignicons.css").read_text(encoding="utf-8")
    return {m.group(1): int(m.group(2), 16)
            for m in re.finditer(r'\.mdi-([a-z0-9-]+)::before \{\s*content: "\\([0-9A-Fa-f]+)"', css)}


def utf8_literal(codepoint: int) -> str:
    return "".join(f"\\x{b:02X}" for b in chr(codepoint).encode("utf-8"))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="only check the names")
    args = parser.parse_args()

    names = sorted(set(tile_icons()) | set(UI_GLYPHS))
    table = codepoints()
    missing = [n for n in names if n not in table]
    if missing:
        sys.exit("not in MDI " + MDI_VERSION + ": " + ", ".join(missing))
    print(f"{len(names)} icons")
    if args.check:
        return

    write_sprite(names)

    ttf = fetch("materialdesignicons-webfont.ttf")
    npx = shutil.which(FONT_CONV[0])
    if npx is None:
        sys.exit("npx was not found: install Node.js")
    symbols = ",".join(f"0x{table[n]:X}" for n in names)
    OUT_FONTS.mkdir(parents=True, exist_ok=True)
    for size, bpp in SIZES:
        out = OUT_FONTS / f"hc_mdi_{size}.c"
        # relative paths: the options line in the file stays the same on every machine
        subprocess.run([npx, *FONT_CONV[1:], "--no-compress", "--format", "lvgl", "--lv-include", "lvgl.h",
                        "--size", str(size), "--bpp", str(bpp), "--font", ttf.relative_to(ROOT).as_posix(),
                        "--range", symbols, "--lv-font-name", out.stem, "-o", out.relative_to(ROOT).as_posix()],
                       cwd=ROOT, check=True)
        out.write_text(out.read_text(encoding="utf-8"), encoding="utf-8", newline="\n")
        print(f"{out.relative_to(ROOT)}: {out.stat().st_size // 1024} KB of source")

    lines = ["// Generated by tools/build_icons.py from the MDI " + MDI_VERSION + " names; do not edit.",
             "// {MDI name, the glyph as UTF-8}, sorted by name."]
    lines += [f'{{"{n}", "{utf8_literal(table[n])}"}},' for n in names]
    OUT_TABLE.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{OUT_TABLE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
