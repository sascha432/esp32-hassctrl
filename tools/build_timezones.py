#!/usr/bin/env python3
"""Builds the time zone table of the firmware: IANA names ("Europe/Berlin", what Home Assistant
reports) to POSIX TZ rules ("CET-1CEST,M3.5.0,M10.5.0/3", what the C library and core::local_time understand).

    python tools/build_timezones.py

The source is the IANA time zone database as the tzdata package on PyPI ships it (Apache-2.0,
the data public domain), the wheel downloaded: the rule of a zone is the POSIX TZ footer of its
TZif file, what the zone does after its last listed transition. The output is committed, so the
build needs no network; run this again when the rules of a country change (a new tzdata release):

    components/core/src/timezones.inc
"""

import io
import json
import urllib.request
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PYPI = "https://pypi.org/pypi/tzdata/json"
OUT = ROOT / "components" / "core" / "src" / "timezones.inc"


def download(url: str) -> bytes:
    with urllib.request.urlopen(url, timeout=60) as response:
        return response.read()


def footer(tzif: bytes) -> str:
    # TZif version 2 and later end with "\n<POSIX TZ rule>\n"
    if not tzif.startswith(b"TZif") or tzif[4:5] < b"2":
        return ""
    return tzif.rstrip(b"\n").rsplit(b"\n", 1)[-1].decode("ascii")


def main() -> None:
    release = json.loads(download(PYPI))
    version = release["info"]["version"]
    wheel = next(f for f in release["urls"] if f["packagetype"] == "bdist_wheel")
    with zipfile.ZipFile(io.BytesIO(download(wheel["url"]))) as archive:
        iana_version = next(
            line.split('"')[1]
            for line in archive.read("tzdata/__init__.py").decode("utf-8").splitlines()
            if line.startswith("IANA_VERSION")
        )
        names = archive.read("tzdata/zones").decode("ascii").split()
        zones = []
        for name in names:
            rule = footer(archive.read(f"tzdata/zoneinfo/{name}"))
            if rule:
                zones.append((name, rule))
    zones.sort()
    # many zones share a rule: each rule once, the zones point at it
    rules = sorted({rule for _, rule in zones})
    index = {rule: i for i, rule in enumerate(rules)}
    lines = [
        f"// Generated by tools/build_timezones.py from tzdata {iana_version} (PyPI tzdata {version}); do not edit.",
        "// kRules: the POSIX TZ rules; kZones: the IANA names, sorted, with the index of their rule.",
        "constexpr const char *kRules[] = {",
    ]
    lines += [f'    "{rule}",' for rule in rules]
    lines += ["};", "constexpr Zone kZones[] = {"]
    lines += [f'    {{"{name}", {index[rule]}}},' for name, rule in zones]
    lines += ["};"]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(ROOT)}: tzdata {iana_version}, {len(zones)} zones, {len(rules)} rules")


if __name__ == "__main__":
    main()
