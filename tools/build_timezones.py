#!/usr/bin/env python3
"""Builds the time zone table of the firmware: IANA names ("Europe/Berlin", what Home Assistant
reports) to POSIX TZ rules ("CET-1CEST,M3.5.0,M10.5.0/3", what the C library understands).

    python tools/build_timezones.py

The source is zones.csv of github.com/nayarsystems/posix_tz_db (MIT license), downloaded. The
output is committed, so the build needs no network; run this again when the rules of a country
change:

    components/platform/src/timezones.inc
"""

import csv
import datetime
import io
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
URL = "https://cdn.jsdelivr.net/gh/nayarsystems/posix_tz_db@master/zones.csv"
OUT = ROOT / "components" / "platform" / "src" / "timezones.inc"


def main() -> None:
    with urllib.request.urlopen(URL, timeout=60) as response:
        rows = list(csv.reader(io.StringIO(response.read().decode("utf-8"))))
    zones = sorted((name, rule) for name, rule in rows if name and rule)
    # many zones share a rule: each rule once, the zones point at it
    rules = sorted({rule for _, rule in zones})
    index = {rule: i for i, rule in enumerate(rules)}
    lines = [
        f"// Generated by tools/build_timezones.py from {URL}",
        f"// ({datetime.date.today().isoformat()}, MIT license); do not edit.",
        "// kRules: the POSIX TZ rules; kZones: the IANA names, sorted, with the index of their rule.",
        "constexpr const char *kRules[] = {",
    ]
    lines += [f'    "{rule}",' for rule in rules]
    lines += ["};", "constexpr Zone kZones[] = {"]
    lines += [f'    {{"{name}", {index[rule]}}},' for name, rule in zones]
    lines += ["};"]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(ROOT)}: {len(zones)} zones, {len(rules)} rules")


if __name__ == "__main__":
    main()
