#!/usr/bin/env python3
"""Writes recovery/font8x8.inc: the glyphs U+0020..U+007E of LVGL's unscii-8 font (public domain,
by Viznut) as 8x8 bitmaps, one byte per row, bit 7 = leftmost pixel. The recovery app draws its
text with it, without LVGL.

    python tools/gen_recovery_font.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "managed_components" / "lvgl__lvgl" / "src" / "font" / "lv_font_unscii_8.c"
OUT = ROOT / "recovery" / "font8x8.inc"

text = SRC.read_text(encoding="utf-8")
bitmap = text[text.index("glyph_bitmap[] = {"):text.index("};", text.index("glyph_bitmap[] = {"))]
data = [int(v, 16) for v in re.findall(r"0x[0-9a-fA-F]+", bitmap)]
dscs = re.findall(
    r"\.bitmap_index = (\d+), \.adv_w = \d+, \.box_w = (\d+), \.box_h = (\d+), \.ofs_x = (-?\d+), \.ofs_y = (-?\d+)", text)
assert len(dscs) == 97, len(dscs)  # id 0 + U+0020..U+007F

lines = []
for code in range(0x20, 0x7F):
    index, w, h, ox, oy = (int(v) for v in dscs[code - 0x20 + 1])
    rows = [0] * 8
    if code != 0x20:
        for y in range(h):
            for x in range(w):
                bit = y * w + x
                if data[index + bit // 8] & (0x80 >> (bit % 8)):
                    row = 8 - h - oy + y
                    col = ox + x
                    assert 0 <= row < 8 and 0 <= col < 8, (chr(code), row, col)
                    rows[row] |= 0x80 >> col
    lines.append("    {" + ", ".join(f"0x{r:02x}" for r in rows) + f"}}, // {chr(code)}")
OUT.write_text("// generated by tools/gen_recovery_font.py\n" + "\n".join(lines).replace("// \\", "// backslash") + "\n",
               encoding="utf-8", newline="\n")
print("wrote", OUT)
